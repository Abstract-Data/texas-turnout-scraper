"""Texas county FIPS codes keyed by county name, for joins that must not depend on spelling.

The roster spells a county ``LASALLE`` and Census sources spell it ``La Salle``; both reduce to
the same :func:`county_key`. Codes are the 5-digit state-plus-county FIPS (``48283``). The table
is generated from ``data/geo/tx_geo.json`` and a test pins it to that file and to the vendored
voterfile reference table. Imported by the Worker: standard library only.
"""

from __future__ import annotations


def county_key(name: str) -> str:
    """A county name compared by its letters only: ``DE WITT`` and ``DeWitt`` are one county."""
    return "".join(ch for ch in name.upper() if ch.isascii() and ch.isalpha())


